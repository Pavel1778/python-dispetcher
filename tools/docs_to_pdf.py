"""Render the NEXUS documents to PDF, with Cyrillic support.

Why this is a checked-in tool rather than a one-off command: the documents are
bilingual, and a PDF pipeline that silently drops Cyrillic glyphs produces boxes
that look like a rendering bug in the reader. Pinning the fonts and the layout here
means the PDFs can be regenerated byte-identically by anyone.

Usage:
    python tools/docs_to_pdf.py                  # all docs/NEXUS_*.md + README
    python tools/docs_to_pdf.py --out docs/pdf   # explicit output directory

Requires: reportlab (dev dependency), DejaVu fonts (present on most Linux images).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (KeepTogether, Paragraph, Preformatted,
                                SimpleDocTemplate, Spacer, Table, TableStyle)

FONT_DIRS = [
    pathlib.Path("/usr/share/fonts/truetype/dejavu"),
    pathlib.Path("/usr/share/fonts/dejavu"),
    pathlib.Path("/usr/share/fonts/truetype/liberation"),
]

#: Files rendered, in reading order. Anything not listed is ignored on purpose:
#: a stray .md in docs/ is not part of the deliverable set.
DOCUMENTS = [
    "NEXUS_MIGRATION_INTEGRITY.md",
    "NEXUS_OPEN_FINDINGS.md",
]


def register_fonts() -> tuple[str, str, str]:
    """Register a Unicode font family. Fails loudly rather than emitting tofu."""
    for directory in FONT_DIRS:
        regular = directory / "DejaVuSans.ttf"
        bold = directory / "DejaVuSans-Bold.ttf"
        mono = directory / "DejaVuSansMono.ttf"
        if regular.is_file() and bold.is_file():
            pdfmetrics.registerFont(TTFont("Body", str(regular)))
            pdfmetrics.registerFont(TTFont("Body-Bold", str(bold)))
            pdfmetrics.registerFont(TTFont("Mono", str(mono if mono.is_file() else regular)))
            return "Body", "Body-Bold", "Mono"
    raise SystemExit(
        "No Unicode font found. Cyrillic would render as empty boxes, so this "
        "refuses to run. Install fonts-dejavu or pass a font directory."
    )


def styles(body: str, bold: str, mono: str) -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle("h1", parent=base["Heading1"], fontName=bold,
                             fontSize=17, leading=21, spaceAfter=8),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontName=bold,
                             fontSize=13, leading=17, spaceBefore=10, spaceAfter=5),
        "h3": ParagraphStyle("h3", parent=base["Heading3"], fontName=bold,
                             fontSize=11.5, leading=15, spaceBefore=8, spaceAfter=4),
        "body": ParagraphStyle("body", parent=base["BodyText"], fontName=body,
                               fontSize=9.5, leading=13.5, alignment=TA_LEFT,
                               spaceAfter=4),
        "bullet": ParagraphStyle("bullet", parent=base["BodyText"], fontName=body,
                                 fontSize=9.5, leading=13.5, leftIndent=12,
                                 bulletIndent=3, spaceAfter=2),
        "code": ParagraphStyle("code", parent=base["Code"], fontName=mono,
                               fontSize=7.6, leading=9.6, textColor=colors.HexColor("#1a1a1a")),
        "quote": ParagraphStyle("quote", parent=base["BodyText"], fontName=body,
                                fontSize=9, leading=12.5, leftIndent=10,
                                textColor=colors.HexColor("#333333"), spaceAfter=6),
    }


INLINE = [
    (re.compile(r"\*\*([^*]+)\*\*"), r"<b>\1</b>"),
    (re.compile(r"(?<!\*)\*([^*]+)\*(?!\*)"), r"<i>\1</i>"),
]

#: Placeholder for a protected code span. A private-use codepoint is used so it
#: cannot collide with document text or with reportlab's mini-markup.
_CODE_TOKEN = "\ue000{}\ue001"


def esc(text: str) -> str:
    """Escape for reportlab's mini-markup, keeping inline code literal.

    Order matters and is the reason this is a function rather than three
    chained ``sub`` calls: ``/api/workflows/*`` inside backticks must not be
    seen by the italic rule, or the emitted XML nests a ``<b>`` inside a wrong
    ``<font>`` and reportlab raises ``ValueError`` at build time. Code spans are
    therefore lifted out first, markup is applied to the remaining prose, and the
    spans are put back already escaped.
    """
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    spans: list[str] = []

    def stash(match: re.Match) -> str:
        spans.append(match.group(1))
        return _CODE_TOKEN.format(len(spans) - 1)

    text = re.sub(r"`([^`]+)`", stash, text)
    for pattern, repl in INLINE:
        text = pattern.sub(repl, text)
    for number, code in enumerate(spans):
        text = text.replace(_CODE_TOKEN.format(number),
                            f'<font name="Mono" size="8.5">{code}</font>')
    return text


def parse_table(lines: list[str], st: dict) -> Table:
    rows = []
    for line in lines:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
            continue
        rows.append([Paragraph(esc(c), st["body"]) for c in cells])
    width = A4[0] - 36 * mm
    columns = max(len(r) for r in rows)
    table = Table(rows, colWidths=[width / columns] * columns, repeatRows=1)
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#bbbbbb")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef1f5")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 3),
        ("RIGHTPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
    ]))
    return table


def render(md_path: pathlib.Path, out_path: pathlib.Path, st: dict) -> None:
    lines = md_path.read_text(encoding="utf-8").split("\n")
    flow: list = []
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        if stripped.startswith("```"):
            block, index = [], index + 1
            while index < len(lines) and not lines[index].strip().startswith("```"):
                block.append(lines[index])
                index += 1
            index += 1
            if block:
                flow.append(Preformatted("\n".join(block), st["code"],
                                         maxLineLength=110))
            flow.append(Spacer(1, 4))
            continue

        if stripped.startswith("|") and index + 1 < len(lines) and \
                re.match(r"^\|?[\s:|-]+\|", lines[index + 1]):
            block = []
            while index < len(lines) and lines[index].strip().startswith("|"):
                block.append(lines[index])
                index += 1
            flow.append(parse_table(block, st))
            flow.append(Spacer(1, 6))
            continue

        if stripped.startswith("#"):
            level = len(stripped) - len(stripped.lstrip("#"))
            text = esc(stripped[level:].strip())
            key = f"h{min(level, 3)}"
            if level == 1:
                flow.append(Spacer(1, 6))
            flow.append(Paragraph(text, st[key]))
            index += 1
            continue

        if stripped.startswith(">"):
            quote = []
            while index < len(lines) and lines[index].strip().startswith(">"):
                quote.append(lines[index].strip().lstrip(">").strip())
                index += 1
            flow.append(KeepTogether(
                Paragraph(esc(" ".join(q for q in quote if q)), st["quote"])))
            continue

        if re.match(r"^[-*]\s+", stripped) or re.match(r"^\d+\.\s+", stripped):
            item = re.sub(r"^([-*]|\d+\.)\s+", "", stripped)
            bullet = "•" if not re.match(r"^\d", stripped) else ""
            flow.append(Paragraph(esc(item), st["bullet"], bulletText=bullet))
            index += 1
            continue

        if stripped in ("---", "***", "___"):
            flow.append(Spacer(1, 8))
            index += 1
            continue

        if not stripped:
            index += 1
            continue

        flow.append(Paragraph(esc(stripped), st["body"]))
        index += 1

    doc = SimpleDocTemplate(
        str(out_path), pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title=md_path.stem, author="NEXUS recovery",
    )

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Body", 7.5)
        canvas.setFillColor(colors.HexColor("#666666"))
        canvas.drawString(18 * mm, 9 * mm, md_path.name)
        canvas.drawRightString(A4[0] - 18 * mm, 9 * mm,
                               f"page {document.page}")
        canvas.restoreState()

    doc.build(flow, onFirstPage=footer, onLaterPages=footer)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render NEXUS docs to PDF")
    parser.add_argument("--out", default="docs/pdf", help="output directory")
    parser.add_argument("--docs", default="docs", help="documentation directory")
    args = parser.parse_args(argv)

    root = pathlib.Path(__file__).resolve().parent.parent
    docs = root / args.docs
    out = root / args.out
    out.mkdir(parents=True, exist_ok=True)

    body, bold, mono = register_fonts()
    st = styles(body, bold, mono)

    rendered, skipped = 0, []
    for name in DOCUMENTS:
        source = docs / name
        if not source.is_file():
            skipped.append(name)
            continue
        target = out / (source.stem + ".pdf")
        render(source, target, st)
        print(f"{source.name:52s} -> {target.relative_to(root)} "
              f"({target.stat().st_size // 1024} KB)")
        rendered += 1

    if skipped:
        print("missing (not rendered): " + ", ".join(skipped), file=sys.stderr)
    print(f"\n{rendered} PDF(s) in {out.relative_to(root)}")
    return 0 if rendered else 1


if __name__ == "__main__":
    raise SystemExit(main())
